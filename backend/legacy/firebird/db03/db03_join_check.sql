-- DB-03 · independent SQL check of the NF header -> line join (Firebird 1.5; uses FK index on ID_NOTA_FISCAL).
-- Compares each header's own QUANTIDADE with the sum of its lines (no ABS in 1.5: BETWEEN tolerance).
SELECT COUNT(*) AS HEADERS,
  SUM(CASE WHEN n.QUANTIDADE IS NULL THEN 1 ELSE 0 END) AS HEADER_QTY_NULL,
  SUM(CASE WHEN n.QUANTIDADE IS NOT NULL AND (n.QUANTIDADE - (SELECT SUM(i.QUANTIDADE) FROM ITENS_NOTA_FISCAL i WHERE i.ID_NOTA_FISCAL = n.ID)) BETWEEN -0.001 AND 0.001 THEN 1 ELSE 0 END) AS HEADER_QTY_MATCH,
  SUM(CASE WHEN n.QUANTIDADE IS NOT NULL AND NOT ((n.QUANTIDADE - (SELECT SUM(i.QUANTIDADE) FROM ITENS_NOTA_FISCAL i WHERE i.ID_NOTA_FISCAL = n.ID)) BETWEEN -0.001 AND 0.001) THEN 1 ELSE 0 END) AS HEADER_QTY_MISMATCH
FROM NOTAS_FISCAIS n;
SELECT n.S_TIPO, COUNT(*) AS HEADERS,
  SUM(CASE WHEN n.QUANTIDADE IS NOT NULL AND NOT ((n.QUANTIDADE - (SELECT SUM(i.QUANTIDADE) FROM ITENS_NOTA_FISCAL i WHERE i.ID_NOTA_FISCAL = n.ID)) BETWEEN -0.001 AND 0.001) THEN 1 ELSE 0 END) AS MISMATCH
FROM NOTAS_FISCAIS n GROUP BY n.S_TIPO;
SELECT COUNT(*) AS LINES_ORPHAN_PRODUCT, COUNT(DISTINCT i.ID_PRODUTO) AS MISSING_PRODUCT_IDS, MIN(i.ID_NOTA_FISCAL) AS MIN_NF, MAX(i.ID_NOTA_FISCAL) AS MAX_NF
FROM ITENS_NOTA_FISCAL i WHERE NOT EXISTS (SELECT 1 FROM PRODUTOS p WHERE p.ID = i.ID_PRODUTO);
SELECT n.S_TIPO, COUNT(*) AS LINES_ORPHAN_PRODUCT FROM ITENS_NOTA_FISCAL i JOIN NOTAS_FISCAIS n ON n.ID = i.ID_NOTA_FISCAL
WHERE NOT EXISTS (SELECT 1 FROM PRODUTOS p WHERE p.ID = i.ID_PRODUTO) GROUP BY n.S_TIPO;
-- Header QUANTIDADE is the header's declared LINE COUNT (verified 2026-11-23: 25,965/25,965).
SELECT COUNT(*) AS HEADERS,
 SUM(CASE WHEN (n.QUANTIDADE - (SELECT COUNT(*) FROM ITENS_NOTA_FISCAL i WHERE i.ID_NOTA_FISCAL = n.ID)) BETWEEN -0.001 AND 0.001 THEN 1 ELSE 0 END) AS HEADER_LINECOUNT_MATCH
FROM NOTAS_FISCAIS n;
