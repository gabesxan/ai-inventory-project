-- DB-03 · key-column export for identity and join checks (Firebird 1.5 SQL).
-- Each data row is prefixed "<TAG>|" and pipe-delimited; db03_extract.sh splits them into
-- local TSV files under $LEGACY_WORK/out/db03 (outside Git). No free-text columns are exported.
SET LIST OFF;

-- NF headers
SELECT 'NF|' || CAST(ID AS VARCHAR(12)) || '|' || COALESCE(CAST(ID_LOJA AS VARCHAR(12)),'') || '|' || COALESCE(S_TIPO,'')
  || '|' || COALESCE(NUMERO,'') || '|' || COALESCE(SERIE,'') || '|' || COALESCE(CAST(MODELO AS VARCHAR(12)),'')
  || '|' || COALESCE(CAST(ID_FORNECEDOR AS VARCHAR(12)),'') || '|' || COALESCE(CAST(ID_CLIENTE AS VARCHAR(12)),'')
  || '|' || CAST(DATA_EMISSAO AS VARCHAR(12)) || '|' || COALESCE(S_NFE_CHAVE_ACESSO,'') || '|' || COALESCE(CAST(I_NFE_STATUS AS VARCHAR(6)),'')
  || '|' || COALESCE(CAST(B_MOVIMENTACAO_ESTOQUE AS VARCHAR(6)),'')
FROM NOTAS_FISCAIS;

-- NF lines
SELECT 'NFI|' || CAST(ID AS VARCHAR(12)) || '|' || CAST(ID_NOTA_FISCAL AS VARCHAR(12)) || '|' || CAST(ID_PRODUTO AS VARCHAR(12))
  || '|' || CAST(QUANTIDADE AS VARCHAR(24))
FROM ITENS_NOTA_FISCAL;

-- Stock movements
SELECT 'ES|' || CAST(ID AS VARCHAR(12)) || '|' || CAST(I_LOJA AS VARCHAR(6)) || '|' || CAST(I_PDV AS VARCHAR(6)) || '|' || S_OPERACAO
  || '|' || CAST(ID_PRODUTO AS VARCHAR(12)) || '|' || CAST(D_DATA AS VARCHAR(12)) || '|' || CAST(F_QUANTIDADE AS VARCHAR(24))
FROM ENTRADAS_SAIDAS;

-- Coupon sale lines
SELECT 'ICC|' || CAST(ID AS VARCHAR(12)) || '|' || COALESCE(CAST(I_LOJA AS VARCHAR(6)),'') || '|' || COALESCE(CAST(I_PDV AS VARCHAR(6)),'')
  || '|' || COALESCE(CAST(D_DATA AS VARCHAR(12)),'') || '|' || COALESCE(S_CUPOM,'') || '|' || COALESCE(CAST(ID_PRODUTO AS VARCHAR(12)),'')
  || '|' || COALESCE(CAST(F_QTD AS VARCHAR(24)),'')
FROM ITENS_CLIENTE_COMPRA;

-- Outbound documents and lines
SELECT 'SP|' || CAST(ID AS VARCHAR(12)) || '|' || COALESCE(CAST(LOJA AS VARCHAR(6)),'') || '|' || COALESCE(TIPO_SAIDA,'') FROM SAIDA_PRODUTOS;
SELECT 'ISP|' || CAST(ID AS VARCHAR(12)) || '|' || COALESCE(CAST(ID_SAIDA_PRODUTOS AS VARCHAR(12)),'') || '|' || COALESCE(CAST(ID_PRODUTO AS VARCHAR(12)),'')
  || '|' || COALESCE(CAST(F_QTD AS VARCHAR(24)),'')
FROM ITENS_SAIDA_PRODUTOS;

-- Products, suppliers, branch configuration (keys only)
SELECT 'PR|' || CAST(ID AS VARCHAR(12)) || '|' || COALESCE(CAST(ID_LOJA AS VARCHAR(6)),'') || '|' || CODIGO_INTERNO || '|' || CODIGO_BARRAS
  || '|' || UNIDADE || '|' || CAST(PESADO AS VARCHAR(3)) || '|' || COALESCE(CAST(ATIVO AS VARCHAR(3)),'')
FROM PRODUTOS;
SELECT 'FO|' || CAST(ID AS VARCHAR(12)) || '|' || CAST(I_NUMERO AS VARCHAR(12)) || '|' || NUMERO || '|' || COALESCE(CNPJ,'') FROM FORNECEDORES;
SELECT 'CF|' || CAST(I_LOJA AS VARCHAR(6)) || '|' || COALESCE(SUBSTRING(S_CNPJ FROM 1 FOR 8),'') FROM CONFIGURACOES;
SELECT 'SL|' || CAST(COUNT(*) AS VARCHAR(12)) FROM SALDO_PRODUTOS;
SELECT 'TE|' || CAST(COUNT(*) AS VARCHAR(12)) FROM TIPOS_ENTRADAS_SAIDAS;
SELECT 'PE|' || CAST(COUNT(*) AS VARCHAR(12)) FROM PEDIDOS;
SELECT 'LJ|' || CAST(COUNT(*) AS VARCHAR(12)) FROM LOJAS;
