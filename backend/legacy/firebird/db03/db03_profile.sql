-- DB-03 · source identities and warehouse scope profile (Firebird 1.5 SQL; aggregates and keys only).
-- Firebird 1.5 has no derived tables: duplicate/collision counts are computed by db03_verify.py.
-- Run against the restored i386 database. Output is raw evidence and stays outside Git.

-- [Q01] Branches (LOJAS): count and whether all branches share one company CNPJ root (first 8 digits).
SELECT COUNT(*) AS LOJAS, COUNT(DISTINCT SUBSTRING(S_CNPJ FROM 1 FOR 8)) AS CNPJ_ROOTS,
       COUNT(DISTINCT S_CNPJ) AS CNPJS, MIN(ID) AS MIN_ID, MAX(ID) AS MAX_ID FROM LOJAS;
SELECT ID, SUBSTRING(S_CNPJ FROM 1 FOR 8) AS CNPJ_ROOT, I_BLOQ FROM LOJAS ORDER BY ID;

-- [Q02] Movement type catalogue and operation codes used in ENTRADAS_SAIDAS.
SELECT ID, S_SIGLA, I_TIPO, DESCRICAO FROM TIPOS_ENTRADAS_SAIDAS ORDER BY ID;
SELECT S_OPERACAO, COUNT(*) AS N, SUM(F_QUANTIDADE) AS QTY, MIN(D_DATA) AS D_MIN, MAX(D_DATA) AS D_MAX
  FROM ENTRADAS_SAIDAS GROUP BY S_OPERACAO ORDER BY 2 DESC;

-- [Q03] Movements by branch and operation.
SELECT I_LOJA, S_OPERACAO, COUNT(*) AS N, COUNT(DISTINCT ID_PRODUTO) AS PRODUCTS,
       COUNT(DISTINCT D_DATA) AS DAYS, MIN(D_DATA) AS D_MIN, MAX(D_DATA) AS D_MAX, SUM(F_QUANTIDADE) AS QTY
  FROM ENTRADAS_SAIDAS GROUP BY I_LOJA, S_OPERACAO ORDER BY I_LOJA, 3 DESC;

-- [Q04] Movement integrity: orphan products, branches missing from LOJAS, negative/zero quantities.
SELECT COUNT(*) AS ORPHAN_PRODUCT FROM ENTRADAS_SAIDAS e WHERE NOT EXISTS (SELECT 1 FROM PRODUTOS p WHERE p.ID = e.ID_PRODUTO);
SELECT COUNT(*) AS UNKNOWN_LOJA FROM ENTRADAS_SAIDAS e WHERE NOT EXISTS (SELECT 1 FROM LOJAS l WHERE l.ID = e.I_LOJA);
SELECT S_OPERACAO, SUM(CASE WHEN F_QUANTIDADE < 0 THEN 1 ELSE 0 END) AS NEG, SUM(CASE WHEN F_QUANTIDADE = 0 THEN 1 ELSE 0 END) AS ZERO
  FROM ENTRADAS_SAIDAS GROUP BY S_OPERACAO;
SELECT COUNT(*) AS WITH_MOV, COUNT(DISTINCT ID_MOVIMENTO) AS DISTINCT_MOV FROM ENTRADAS_SAIDAS WHERE ID_MOVIMENTO IS NOT NULL;

-- [Q05] Products: branch ownership and code uniqueness.
SELECT ID_LOJA, COUNT(*) AS N, SUM(CASE WHEN ATIVO = 1 THEN 1 ELSE 0 END) AS ATIVOS FROM PRODUTOS GROUP BY ID_LOJA;
SELECT COUNT(*) AS PRODUTOS, COUNT(DISTINCT CODIGO_INTERNO) AS COD_INTERNO, COUNT(DISTINCT CODIGO_BARRAS) AS COD_BARRAS FROM PRODUTOS;
SELECT UNIDADE, PESADO, COUNT(*) AS N FROM PRODUTOS GROUP BY UNIDADE, PESADO ORDER BY 3 DESC;

-- [Q06] Per-branch stock rows (SALDO_PRODUTOS): one row per (product, branch)?
SELECT ID_LOJA, COUNT(*) AS N, COUNT(DISTINCT ID_PRODUTO) AS PRODUCTS FROM SALDO_PRODUTOS GROUP BY ID_LOJA;

-- [Q07] Locations.
SELECT COUNT(*) AS LOCALIZACOES FROM LOCALIZACOES;
SELECT COUNT(*) AS PROD_WITH_LOC, COUNT(DISTINCT LOCALIZACAO) AS LOCS_USED FROM PRODUTOS WHERE LOCALIZACAO IS NOT NULL AND LOCALIZACAO <> 0;

-- [Q08] Suppliers.
SELECT COUNT(*) AS FORNECEDORES, COUNT(DISTINCT I_NUMERO) AS I_NUMERO, COUNT(DISTINCT NUMERO) AS NUMERO,
       COUNT(DISTINCT CNPJ) AS CNPJ, SUM(CASE WHEN CNPJ IS NULL OR CNPJ = '' THEN 1 ELSE 0 END) AS NO_CNPJ FROM FORNECEDORES;

-- [Q09] Fiscal documents (NOTAS_FISCAIS) by branch and type, and document-number collisions across branches.
SELECT ID_LOJA, S_TIPO, COUNT(*) AS N, COUNT(DISTINCT NUMERO) AS NUMEROS, MIN(DATA_EMISSAO) AS D_MIN, MAX(DATA_EMISSAO) AS D_MAX
  FROM NOTAS_FISCAIS GROUP BY ID_LOJA, S_TIPO ORDER BY 1, 2;

-- [Q10] NF header -> lines.
SELECT COUNT(*) AS NF_HEADERS FROM NOTAS_FISCAIS;
SELECT COUNT(*) AS NF_LINES, COUNT(DISTINCT ID_NOTA_FISCAL) AS HEADERS_WITH_LINES, SUM(QUANTIDADE) AS QTY FROM ITENS_NOTA_FISCAL;
SELECT COUNT(*) AS ORPHAN_NF_LINES FROM ITENS_NOTA_FISCAL i WHERE NOT EXISTS (SELECT 1 FROM NOTAS_FISCAIS n WHERE n.ID = i.ID_NOTA_FISCAL);
SELECT COUNT(*) AS JOINED_LINES, SUM(i.QUANTIDADE) AS JOINED_QTY FROM NOTAS_FISCAIS n JOIN ITENS_NOTA_FISCAL i ON i.ID_NOTA_FISCAL = n.ID;
SELECT MAX(QUANTIDADE) AS MAX_QTY, SUM(CASE WHEN QUANTIDADE >= 99 THEN 1 ELSE 0 END) AS NEAR_CAP FROM ITENS_NOTA_FISCAL;

-- [Q11] Purchase orders (PEDIDOS) -> lines.
SELECT ID_LOJA, S_STATUS, COUNT(*) AS N, MIN(D_DATA_PEDIDO) AS D_MIN, MAX(D_DATA_PEDIDO) AS D_MAX FROM PEDIDOS GROUP BY ID_LOJA, S_STATUS;
SELECT COUNT(*) AS PO_LINES, COUNT(DISTINCT ID_PEDIDO) AS PO_WITH_LINES, SUM(QUANTIDADE) AS QTY FROM ITENS_PEDIDO;
SELECT COUNT(*) AS ORPHAN_PO_LINES FROM ITENS_PEDIDO i WHERE NOT EXISTS (SELECT 1 FROM PEDIDOS p WHERE p.ID = i.ID_PEDIDO);
SELECT COUNT(*) AS PO_ORPHAN_SUPPLIER FROM PEDIDOS p WHERE NOT EXISTS (SELECT 1 FROM FORNECEDORES f WHERE f.ID = p.ID_FORNECEDOR);

-- [Q12] Customer sale lines with coupon (ITENS_CLIENTE_COMPRA) and seller sales (VENDEDORES_VENDAS).
SELECT I_LOJA, COUNT(*) AS N, COUNT(DISTINCT D_DATA) AS DAYS, MIN(D_DATA) AS D_MIN, MAX(D_DATA) AS D_MAX FROM ITENS_CLIENTE_COMPRA GROUP BY I_LOJA;
SELECT S_OPERACAO, COUNT(*) AS N, MIN(D_DATA) AS D_MIN, MAX(D_DATA) AS D_MAX FROM VENDEDORES_VENDAS GROUP BY S_OPERACAO;

-- [Q13] Outbound documents (SAIDA_PRODUTOS) -> lines.
SELECT LOJA, TIPO_SAIDA, COUNT(*) AS N FROM SAIDA_PRODUTOS GROUP BY LOJA, TIPO_SAIDA;
SELECT COUNT(*) AS LINES, COUNT(DISTINCT ID_SAIDA_PRODUTOS) AS HEADERS_WITH_LINES FROM ITENS_SAIDA_PRODUTOS;
