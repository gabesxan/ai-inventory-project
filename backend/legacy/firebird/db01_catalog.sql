-- DB-01 catalog fingerprint (aggregate metadata only).
SET LIST ON;
SELECT RDB$CHARACTER_SET_NAME AS DB_DEFAULT_CHARSET FROM RDB$DATABASE;
SELECT rdb$get_context('SYSTEM','ENGINE_VERSION') AS ENGINE_VERSION FROM RDB$DATABASE;
SELECT
 (SELECT COUNT(*) FROM RDB$RELATIONS WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0 AND RDB$VIEW_BLR IS NULL) AS USER_TABLES,
 (SELECT COUNT(*) FROM RDB$RELATIONS WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0 AND RDB$VIEW_BLR IS NOT NULL) AS USER_VIEWS,
 (SELECT COUNT(*) FROM RDB$RELATION_FIELDS rf JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME=rf.RDB$RELATION_NAME
   WHERE COALESCE(r.RDB$SYSTEM_FLAG,0)=0) AS USER_COLUMNS,
 (SELECT COUNT(*) FROM RDB$PROCEDURES WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0) AS PROCEDURES,
 (SELECT COUNT(*) FROM RDB$TRIGGERS WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0) AS TRIGGERS,
 (SELECT COUNT(*) FROM RDB$GENERATORS WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0) AS GENERATORS,
 (SELECT COUNT(*) FROM RDB$INDICES WHERE COALESCE(RDB$SYSTEM_FLAG,0)=0) AS INDICES,
 (SELECT COUNT(*) FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_TYPE='PRIMARY KEY') AS PRIMARY_KEYS,
 (SELECT COUNT(*) FROM RDB$RELATION_CONSTRAINTS WHERE RDB$CONSTRAINT_TYPE='FOREIGN KEY') AS FOREIGN_KEYS,
 (SELECT COUNT(*) FROM RDB$FUNCTIONS) AS UDFS
FROM RDB$DATABASE;
SET LIST OFF;
-- Character sets used by user text columns.
SELECT TRIM(COALESCE(cs.RDB$CHARACTER_SET_NAME,'(default)')) AS COLUMN_CHARSET, COUNT(*) AS TEXT_COLUMNS
FROM RDB$RELATION_FIELDS rf
JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = rf.RDB$RELATION_NAME
JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME = rf.RDB$FIELD_SOURCE
LEFT JOIN RDB$CHARACTER_SETS cs ON cs.RDB$CHARACTER_SET_ID = f.RDB$CHARACTER_SET_ID
WHERE COALESCE(r.RDB$SYSTEM_FLAG,0)=0 AND f.RDB$FIELD_TYPE IN (14,37)
GROUP BY 1;
-- UDF libraries referenced by the schema (must exist in the target engine for some queries).
SELECT DISTINCT TRIM(RDB$MODULE_NAME) AS UDF_MODULE FROM RDB$FUNCTIONS;
